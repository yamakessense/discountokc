def build_deploy():
    if os.path.isdir(SITEDIR):
        shutil.rmtree(SITEDIR)
    os.makedirs(os.path.join(SITEDIR, "assets"), exist_ok=True)
    with open(os.path.join(SITEDIR, "assets", "site.css"), "w", encoding="utf-8") as f:
        f.write(CSS)
    # Everything in assets/ ships as-is: logo, favicons, social card, photos/.
    shutil.copytree(ASSETS_DIR, os.path.join(SITEDIR, "assets"), dirs_exist_ok=True)

    # Bing's crawler, and plenty of feed readers and link unfurlers, request
    # /favicon.ico straight off the site root and never read the <link> tags.
    # Ship a copy at the top of the published tree so that request resolves.
    # After DNS cutover this IS the domain root; on the project-page test URL
    # it is the root of everything we control.
    for name in ("favicon.ico", "apple-touch-icon.png"):
        src = os.path.join(ASSETS_DIR, name)
        if os.path.isfile(src):
            shutil.copyfile(src, os.path.join(SITEDIR, name))
    pages = build_pages(dep_link)
    urls = []
    for p in pages:
        body = render_body(p, dep_link)
        d = SITEDIR if p["slug"] == "" else os.path.join(SITEDIR, p["slug"])
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "index.html"), "w", encoding="utf-8") as f:
            f.write(full_page(p, body, dep_link))
        urls.append(SITE + "/" + (p["slug"] + "/" if p["slug"] else ""))

    # 404
    nf = dict(slug="404", nav="", title="Page not found | " + BIZ, desc="Page not found.",
              h1="That page isn't here", lead="It may have moved. Try a category below, or call the store.",
              paras=["If you were looking for something specific, call Midwest City at 405-206-8111 or South OKC at "
                     "405-479-7918 and we'll point you the right way."],
              extra=lambda L: cat_grid(L), faq=[])
    body404 = f'''<div class="pagehead"><div class="wrap"><h1>{nf['h1']}</h1>
<p class="lead">{nf['lead']}</p></div></div>
<section><div class="wrap"><p>{nf['paras'][0]}</p>{cat_grid(dep_link)}</div></section>'''
    with open(os.path.join(SITEDIR, "404.html"), "w", encoding="utf-8") as f:
        f.write(f'''<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>{nf['title']}</title>
<meta name="robots" content="noindex">{FONTS}<link rel="stylesheet" href="{BASE}/assets/site.css">
<link rel="icon" href="{BASE}/assets/favicon.ico" sizes="any">
<link rel="icon" type="image/png" sizes="32x32" href="{BASE}/assets/favicon-32.png">
<link rel="apple-touch-icon" sizes="180x180" href="{BASE}/assets/apple-touch-icon.png"></head><body>
{topbar(dep_link)}{masthead(dep_link)}{catnav(dep_link,'')}<main>{body404}</main>{footer(dep_link)}</body></html>''')

    with open(os.path.join(SITEDIR, "sitemap.xml"), "w", encoding="utf-8") as f:
        today = __import__("datetime").date.today().isoformat()
        items = "".join(
            f"<url><loc>{u}</loc><lastmod>{today}</lastmod><changefreq>weekly</changefreq>"
            f"<priority>{'1.0' if u.rstrip('/').endswith('.com') else '0.8'}</priority></url>"
            for u in urls)
        f.write('<?xml version="1.0" encoding="UTF-8"?>'
                f'<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{items}</urlset>')
    with open(os.path.join(SITEDIR, "robots.txt"), "w", encoding="utf-8") as f:
        f.write(f"User-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n")
    if WRITE_CNAME:
        with open(os.path.join(SITEDIR, "CNAME"), "w", encoding="utf-8") as f:
            f.write("www.discountokc.com\n")
    return pages


